"""Hybrid Ensemble Risk Fusion for Pre-Ingestion Security Gate.

Integrates all four security detectors:
1. Enhanced Perplexity Analysis
2. Similarity / Outlier Analysis
3. Semantic Analysis
4. Direct Prompt-Injection Analysis

Normalizes all detector scores, computes weighted risk aggregation,
records individual detector contributions, and produces structured security verdicts.
"""

from dataclasses import dataclass, field
from datetime import datetime
from typing import Any, Dict, List, Optional, Tuple
import numpy as np

from ragshield.core.document import Document
from ragshield.detection.base import DetectionResult, ThreatLevel
from ragshield.detection.perplexity import PerplexityDetector
from ragshield.detection.similarity import SimilarityDetector
from ragshield.detection.semantic import SemanticDetector
from ragshield.detection.prompt_injection import PromptInjectionDetector


@dataclass
class FusionWeights:
    """Configurable weights for the four security detectors.

    Must sum to 1.0.
    """

    perplexity: float = 0.20
    similarity: float = 0.25
    semantic: float = 0.25
    prompt_injection: float = 0.30

    def __post_init__(self):
        total = self.perplexity + self.similarity + self.semantic + self.prompt_injection
        if not (0.99 <= total <= 1.01):
            # Normalize to 1.0
            self.perplexity /= total
            self.similarity /= total
            self.semantic /= total
            self.prompt_injection /= total

    def to_dict(self) -> Dict[str, float]:
        return {
            "perplexity": self.perplexity,
            "similarity": self.similarity,
            "semantic": self.semantic,
            "prompt_injection": self.prompt_injection,
        }


@dataclass
class UnifiedSecurityResult:
    """Structured security decision generated by the Hybrid Ensemble Risk Fusion mechanism."""

    chunk_id: str
    decision: str  # "safe" or "suspicious"
    unified_risk_score: float  # Normalized score in [0.0, 1.0]
    threshold: float
    threat_level: ThreatLevel
    confidence: float
    detector_scores: Dict[str, float]  # Normalized score for each detector
    raw_scores: Dict[str, Any]  # Raw metrics (e.g. raw perplexity value)
    detector_contributions: Dict[str, float]  # Percentage contribution to total risk
    dominant_detector: str
    reasons: List[str]
    flagged_evidence: List[str]
    timestamp: str = field(default_factory=lambda: datetime.now().isoformat())

    @property
    def is_safe(self) -> bool:
        return self.decision == "safe"

    @property
    def is_suspicious(self) -> bool:
        return self.decision == "suspicious"

    def to_dict(self) -> Dict[str, Any]:
        return {
            "chunk_id": self.chunk_id,
            "decision": self.decision,
            "unified_risk_score": self.unified_risk_score,
            "threshold": self.threshold,
            "threat_level": self.threat_level.value,
            "confidence": self.confidence,
            "detector_scores": self.detector_scores,
            "raw_scores": self.raw_scores,
            "detector_contributions": self.detector_contributions,
            "dominant_detector": self.dominant_detector,
            "reasons": self.reasons,
            "flagged_evidence": self.flagged_evidence,
            "timestamp": self.timestamp,
        }


class HybridRiskFusion:
    """Ensemble Risk Fusion Engine uniting all 4 pre-ingestion security detectors.

    Aggregates:
    1. Perplexity Analysis (token-level NLL anomaly)
    2. Similarity / Outlier Analysis (embedding manifold deviation)
    3. Semantic Analysis (inconsistency, contradictions, instruction patterns)
    4. Direct Prompt-Injection Analysis (explicit command override & exfiltration)
    """

    def __init__(
        self,
        perplexity_detector: Optional[PerplexityDetector] = None,
        similarity_detector: Optional[SimilarityDetector] = None,
        semantic_detector: Optional[SemanticDetector] = None,
        prompt_injection_detector: Optional[PromptInjectionDetector] = None,
        weights: Optional[FusionWeights] = None,
        decision_threshold: float = 0.50,
    ):
        self.perplexity_detector = perplexity_detector or PerplexityDetector()
        self.similarity_detector = similarity_detector or SimilarityDetector()
        self.semantic_detector = semantic_detector or SemanticDetector()
        self.prompt_injection_detector = prompt_injection_detector or PromptInjectionDetector()

        self.weights = weights or FusionWeights()
        self.decision_threshold = decision_threshold

    def evaluate_chunk(self, document: Document) -> UnifiedSecurityResult:
        """Execute all four detectors on a document chunk and fuse their scores."""
        # 1. Detector 1: Perplexity
        res_ppl = self.perplexity_detector.detect(document)
        score_ppl = float(
            np.clip(
                res_ppl.metadata.get(
                    "normalized_score",
                    self.perplexity_detector.normalize_score(res_ppl.score),
                ),
                0.0,
                1.0,
            )
        )

        # 2. Detector 2: Similarity / Outlier
        res_sim = self.similarity_detector.detect(document)
        score_sim = float(
            np.clip(
                res_sim.metadata.get("outlier_score", res_sim.score),
                0.0,
                1.0,
            )
        )

        # 3. Detector 3: Semantic
        res_sem = self.semantic_detector.detect(document)
        score_sem = float(np.clip(res_sem.score, 0.0, 1.0))

        # 4. Detector 4: Direct Prompt-Injection
        res_inj = self.prompt_injection_detector.detect(document)
        score_inj = float(np.clip(res_inj.score, 0.0, 1.0))

        scores = {
            "perplexity": score_ppl,
            "similarity": score_sim,
            "semantic": score_sem,
            "prompt_injection": score_inj,
        }

        w = self.weights.to_dict()

        # Weighted Unified Risk Score: R = sum(w_k * s_k)
        unified_risk = (
            w["perplexity"] * score_ppl
            + w["similarity"] * score_sim
            + w["semantic"] * score_sem
            + w["prompt_injection"] * score_inj
        )
        # In presence of high-confidence direct prompt injection or critical semantic override,
        # ensure unified risk score reflects the critical severity
        if score_inj >= 0.80:
            unified_risk = max(unified_risk, score_inj * 0.75)
        elif score_sem >= 0.50:
            unified_risk = max(unified_risk, score_sem * 0.80)

        unified_risk = float(np.clip(unified_risk, 0.0, 1.0))

        # Compute percentage contribution of each detector to the total weighted risk
        # Normalizing by sum(w_k * s_k) guarantees mathematically valid attributions summing to exactly 100%
        weighted_sum = sum(w[k] * scores[k] for k in scores.keys())
        contributions: Dict[str, float] = {}
        if weighted_sum > 1e-6:
            for k, s in scores.items():
                contributions[k] = round((w[k] * s / weighted_sum) * 100.0, 2)
            current_sum = sum(contributions.values())
            diff = round(100.0 - current_sum, 2)
            if diff != 0.0:
                dom_k = max(scores.keys(), key=lambda k: w[k] * scores[k])
                contributions[dom_k] = round(contributions[dom_k] + diff, 2)
        else:
            for k in scores.keys():
                contributions[k] = 25.0

        # Identify dominant detector
        dominant_detector = max(scores.keys(), key=lambda k: w[k] * scores[k])

        # Security Decision
        # Critical override: if direct prompt injection or critical threat is confirmed with high confidence (>=0.80),
        # force suspicious verdict even if other detectors are low.
        forced_injection = (score_inj >= 0.80) or (score_sem >= 0.50 and len(res_sem.metadata.get("evidence_spans", [])) > 0)
        is_suspicious = (unified_risk >= self.decision_threshold) or forced_injection

        decision = "suspicious" if is_suspicious else "safe"

        # Determine aggregate threat level
        if not is_suspicious:
            threat_level = ThreatLevel.NONE
        elif unified_risk >= 0.80 or forced_injection:
            threat_level = ThreatLevel.CRITICAL
        elif unified_risk >= 0.65:
            threat_level = ThreatLevel.HIGH
        else:
            threat_level = ThreatLevel.MEDIUM

        # Collect reasons and evidence
        reasons = []
        evidence = []

        if res_ppl.is_poisoned:
            reasons.append(f"[Perplexity] {res_ppl.reason}")
        if res_sim.is_poisoned:
            reasons.append(f"[Similarity] {res_sim.reason}")
        if res_sem.is_poisoned:
            reasons.append(f"[Semantic] {res_sem.reason}")
            evidence.extend(res_sem.metadata.get("evidence_spans", []))
        if res_inj.is_poisoned:
            reasons.append(f"[PromptInjection] {res_inj.reason}")
            evidence.extend(res_inj.metadata.get("evidence", []))

        if not reasons:
            reasons.append("All detectors validated chunk within safe linguistic and semantic tolerances.")

        # Aggregate confidence
        confidence = float(min(0.99, max(0.50, 0.50 + abs(unified_risk - self.decision_threshold))))

        raw_metrics = {
            "perplexity_raw": res_ppl.metadata.get("raw_perplexity", 0.0),
            "perplexity_loss": res_ppl.metadata.get("avg_nll_loss", 0.0),
            "similarity_outlier_distance": res_sim.metadata.get("reference_outlier_distance", 0.0),
            "similarity_stat_flags": res_sim.metadata.get("stat_flags", 0),
            "semantic_keyword_matches": res_sem.metadata.get("keyword_matches", []),
            "prompt_injection_rules": res_inj.metadata.get("matched_rules", []),
        }

        return UnifiedSecurityResult(
            chunk_id=document.doc_id or "unknown_chunk",
            decision=decision,
            unified_risk_score=round(unified_risk, 4),
            threshold=self.decision_threshold,
            threat_level=threat_level,
            confidence=round(confidence, 4),
            detector_scores={k: round(v, 4) for k, v in scores.items()},
            raw_scores=raw_metrics,
            detector_contributions=contributions,
            dominant_detector=dominant_detector,
            reasons=reasons,
            flagged_evidence=list(dict.fromkeys(evidence)),  # deduplicate preserving order
        )

    def calibrate(
        self,
        benign_chunks: List[Document],
        validation_poison_chunks: Optional[List[Document]] = None,
        target_fpr: float = 0.05,
    ) -> float:
        """Calibrate ensemble threshold on validation data to achieve target False Positive Rate (FPR)."""
        if not benign_chunks:
            return self.decision_threshold

        benign_scores = [self.evaluate_chunk(doc).unified_risk_score for doc in benign_chunks]
        # Choose threshold at (100 - target_fpr * 100) percentile of benign scores
        calibrated_threshold = float(np.percentile(benign_scores, 100.0 * (1.0 - target_fpr)))
        self.decision_threshold = max(0.30, min(0.85, calibrated_threshold))
        return self.decision_threshold
